let current = null;

export function storedLanguage() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    return LANGUAGES.some((l) => l.id === saved) ? saved : null;
  } catch {
    return null;
  }
}

function guessLanguage() {
  const nav = typeof navigator === 'undefined' ? {} : navigator;
  const wanted = (nav.languages ?? [nav.language ?? '']).map((tag) =>
    String(tag).slice(0, 2).toLowerCase());
  return wanted.find((code) => LANGUAGES.some((l) => l.id === code)) ?? 'en';
}


export async function loadLanguage() {
  const id = getLanguage();
  if (id === 'en' || STRINGS[id]) return;
  try {
    const pack = await import('./i18n-fr.js');
    STRINGS.fr = pack.fr;
  } catch {
  }
}

let languageSource = null;

export function useLanguageSource(source) {
  languageSource = source;
}

export function getLanguage() {
  const ambient = languageSource?.();
  if (ambient && LANGUAGES.some((l) => l.id === ambient)) return ambient;
  if (!current) current = storedLanguage() ?? guessLanguage();
  return current;
}

export function setLanguage(id) {
  if (!LANGUAGES.some((l) => l.id === id)) return getLanguage();
  current = id;
  try { localStorage.setItem(LANG_KEY, id); touch(LANG_KEY); } catch {}
  touch();
  return current;
}

export const languageChosen = () => storedLanguage() !== null;

export const wikiLang = () =>
  LANGUAGES.find((l) => l.id === getLanguage())?.wiki ?? 'en';

const pluralRules = new Map();

export function isSingular(n, lang = getLanguage()) {
  const value = typeof n === 'number' ? n : typeof n === 'string' && /^-?\d+$/.test(n.trim()) ? Number(n) : NaN;
  if (!Number.isFinite(value)) return false;
  if (!pluralRules.has(lang)) pluralRules.set(lang, new Intl.PluralRules(lang));
  return pluralRules.get(lang).select(value) === 'one';
}

function pick(table, key, vars) {
  if (!('n' in vars) || !isSingular(vars.n)) return table[key] ?? STRINGS.en[key];
  const one = `${key}_one`;
  if (table[key] !== undefined) return table[one] ?? table[key];
  return STRINGS.en[one] ?? STRINGS.en[key];
}

export function t(key, vars = {}) {
  const table = STRINGS[getLanguage()] ?? STRINGS.en;
  const raw = pick(table, key, vars) ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : `{${name}}`);
}

export function tx(value) {
  if (typeof value === 'string') return value;
  if (!value) return '';
  return value[getLanguage()] ?? value.en ?? '';
}
